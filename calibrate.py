def main():
    head = (f"{'input':<18} {'model':>6} {'style':>6} {'comb':>6}  "
            f"{'spread':>6} {'ttr':>6} {'punct':>6}  guess")
    print(head)
    print("-" * len(head))
    for name, text in INPUTS.items():
        model = detector.model_signal(text)
        style = stylometry.style_signal(text)
        combined = scoring.combine_signals(model, style)
        guess, _ = scoring.score_to_label(combined)
        raw = (stylometry.sentence_length_spread(text),
               stylometry.type_token_ratio(text),
               stylometry.punctuation_density(text))
        print(f"{name:<18} {model:>6.3f} {style:>6.3f} {combined:>6.3f}  "
              f"{raw[0]:>6.3f} {raw[1]:>6.3f} {raw[2]:>6.2f}  {guess}")
    print("\nmodel/style/comb: 0 human … 1 AI.  spread/ttr/punct: raw, higher = more human.")


if __name__ == "__main__":
    main()
